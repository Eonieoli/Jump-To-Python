# 인덱싱
t1 = (1, 2, 'a', 'b')
print(t1[0])
print(t1[3])

# 슬라이싱
t2 = (1, 2, 'a', 'b')
print(t1[1:])

# 튜플 더하기
t1 = (1, 2, 'a', 'b')
t2 = (3, 4)
t3 = t1 + t2
print(t3)

# 튜플 곱하기
t2 = (3, 4)
t3 = t2 * 3
print(t3)

# 튜플 길이 구하기
t1 = (1, 2, 'a', 'b')
print(len(t1))

# 1분 코딩
